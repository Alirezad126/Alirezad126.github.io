/**
 * Generates src/data/techIcons.js from simple-icons, so the site ships only the
 * handful of path strings it needs instead of the whole icon package.
 *
 * Run with: node scripts/build-tech-icons.mjs
 */
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const icons = Object.values(require('simple-icons')).filter((i) => i && i.title)

// Skill name in portfolio.js -> simple-icons title. Anything absent here falls
// back to a monogram in the UI.
const map = {
  Python: 'Python',
  pandas: 'pandas',
  NumPy: 'NumPy',
  PySpark: 'Apache Spark',
  Gurobi: 'Gurobi',
  PyTorch: 'PyTorch',
  'scikit-learn': 'scikit-learn',
  'OpenAI Gym': 'OpenAI Gym',
  'Git & CI/CD': 'Git',
  Docker: 'Docker',
  MLflow: 'MLflow',
  'Azure Databricks': 'Databricks',
  FastAPI: 'FastAPI',
  PostgreSQL: 'PostgreSQL',
  Snowflake: 'Snowflake'
}

const out = {}
const missing = []

for (const [skill, title] of Object.entries(map)) {
  const icon = icons.find((i) => i.title.toLowerCase() === title.toLowerCase())
  if (icon) out[skill] = icon.path
  else missing.push(title)
}

if (missing.length) {
  console.error('No icon found for:', missing.join(', '))
  process.exit(1)
}

const body = `// Generated by scripts/build-tech-icons.mjs — do not edit by hand.
// 24x24 viewBox path data from simple-icons, rendered in currentColor.
const techIcons = ${JSON.stringify(out, null, 2)}

export default techIcons
`

writeFileSync(new URL('../src/data/techIcons.js', import.meta.url), body)
console.log(`Wrote ${Object.keys(out).length} icons.`)
